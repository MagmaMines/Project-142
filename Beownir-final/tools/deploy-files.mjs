#!/usr/bin/env node
/**
 * Host-specific deploy metadata, generated from netlify.toml so the two can
 * never disagree.
 *
 * Netlify reads `netlify.toml`; Cloudflare Pages (and GitHub Pages with a
 * worker, and most other static hosts) read a `_headers` file in the publish
 * directory. Cross-origin isolation is not optional for this product — without
 * these headers the runtime still boots, but in the limited profile — so the
 * `_headers` file is generated and checked rather than hand-maintained.
 *
 *   node tools/deploy-files.mjs          # verify o/site/_headers matches netlify.toml
 *   node tools/deploy-files.mjs --write  # regenerate it
 *   node tools/deploy-files.mjs --print  # print the file to stdout
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseConfig } from './serve-static.mjs';

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const netlifyConfig = path.join(root, 'netlify.toml');
export const headersPath = path.join(root, 'o', 'site', '_headers');

/* Header names Cloudflare treats specially are still written verbatim; the only
 * rule that matters here is the file format: a path pattern, then indented
 * `Name: value` lines, blocks separated by a blank line. */
export function renderHeaders(config) {
  const blocks = [];
  for (const block of config.headers) {
    const lines = ['for = ' + block.for];
    const pairs = Object.entries(block.values);
    if (!pairs.length) throw new Error('header block for "' + block.for + '" has no values');
    blocks.push([block.for, ...pairs.map(([name, value]) => '  ' + name + ': ' + value)].join('\n'));
  }
  return '# Generated by tools/deploy-files.mjs from netlify.toml. Do not edit.\n' +
    '# Cloudflare Pages / static hosts read this file; Netlify reads netlify.toml.\n\n' +
    blocks.join('\n\n') + '\n';
}

export function expected(configFile = netlifyConfig) {
  return renderHeaders(parseConfig(fs.readFileSync(configFile, 'utf8')));
}

/** Returns a list of human-readable problems; empty means the file is current. */
export function checkHeaders(file = headersPath, configFile = netlifyConfig) {
  const want = expected(configFile);
  if (!fs.existsSync(file)) return ['missing ' + path.relative(root, file) + ' (run node tools/deploy-files.mjs --write)'];
  const have = fs.readFileSync(file, 'utf8');
  if (have === want) return [];
  const wantLines = want.split('\n');
  const haveLines = have.split('\n');
  const problems = [path.relative(root, file) + ' differs from netlify.toml'];
  for (let index = 0; index < Math.max(wantLines.length, haveLines.length); index++) {
    if (wantLines[index] !== haveLines[index]) {
      problems.push('  line ' + (index + 1) + ': expected ' + JSON.stringify(wantLines[index]) + ', found ' + JSON.stringify(haveLines[index]));
      break;
    }
  }
  problems.push('  run node tools/deploy-files.mjs --write');
  return problems;
}

export function writeHeaders(file = headersPath, configFile = netlifyConfig) {
  fs.writeFileSync(file, expected(configFile));
  return file;
}

/* The isolation headers, as they must appear on every response. Kept here so the
 * deploy tests have one definition to assert against. */
export const ISOLATION = {
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Cross-Origin-Embedder-Policy': 'require-corp',
};

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  if (process.argv.includes('--print')) {
    process.stdout.write(expected());
  } else if (process.argv.includes('--write')) {
    writeHeaders();
    console.log('wrote ' + path.relative(root, headersPath));
  } else {
    const problems = checkHeaders();
    if (problems.length) {
      console.error(problems.join('\n'));
      process.exitCode = 1;
    } else {
      console.log('o/site/_headers matches netlify.toml (' + parseConfig(fs.readFileSync(netlifyConfig, 'utf8')).headers.length + ' blocks)');
    }
  }
}
