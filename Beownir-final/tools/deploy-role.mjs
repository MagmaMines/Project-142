#!/usr/bin/env node
/**
 * Prepares one Netlify site of the three-origin native deployment.
 *
 *   BEOWNIR_ROLE=ide|runtime|preview
 *   BEOWNIR_IDE_ORIGIN, BEOWNIR_RUNTIME_ORIGIN, BEOWNIR_PREVIEW_ORIGIN   (or the flags below)
 *
 *   node tools/deploy-role.mjs --role ide --ide https://a.netlify.app \
 *        --runtime https://b.netlify.app --preview https://c.netlify.app [--out dist]
 *
 * Writes dist/index.html (the origins are baked into <meta name="beownir-origins">, so the
 * page starts configured) and dist/_headers for the role. The committed artifact is not touched.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ROLES = new Set(['ide', 'runtime', 'preview']);

// Same rules as the page's own origin check: https, or http on localhost; origin only.
export function cleanOrigin(value, name) {
  let url;
  try { url = new URL(String(value || '').trim()); } catch { throw new Error(name + ' is not a valid URL: ' + value); }
  const local = url.hostname === 'localhost' || url.hostname === '127.0.0.1';
  if (url.protocol !== 'https:' && !(url.protocol === 'http:' && local)) throw new Error(name + ' must be https (or http on localhost): ' + value);
  if (url.username || url.password || url.pathname !== '/' || url.search || url.hash) throw new Error(name + ' must be a bare origin with no path, query or credentials: ' + value);
  return url.origin;
}

export function resolveOrigins(input) {
  const ide = cleanOrigin(input.ide, 'IDE origin');
  const runtime = cleanOrigin(input.runtime, 'runtime origin');
  const preview = cleanOrigin(input.preview, 'preview origin');
  if (new Set([ide, runtime, preview]).size !== 3) throw new Error('IDE, runtime and preview must be three distinct origins');
  return { ide, runtime, preview };
}

export function headersFor(role, origins) {
  if (!ROLES.has(role)) throw new Error('unknown role: ' + role);
  const common = [
    'Cross-Origin-Opener-Policy: same-origin',
    'Cross-Origin-Embedder-Policy: require-corp',
    'Origin-Agent-Cluster: ?1',
    'X-Content-Type-Options: nosniff',
    'Referrer-Policy: no-referrer',
  ];
  const lines = ['# Generated by tools/deploy-role.mjs for role ' + role + '. Do not edit.', '', '/*'];
  if (role === 'ide') {
    lines.push(...common.map(h => '  ' + h));
    lines.push('  Cross-Origin-Resource-Policy: same-origin');
    lines.push('  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), cross-origin-isolated=(self "' + origins.runtime + '" "' + origins.preview + '")');
    lines.push('', '/index.html', '  Cache-Control: public, max-age=0, must-revalidate', '', '/', '  Cache-Control: public, max-age=0, must-revalidate');
    lines.push('', '/coi-sw.js', '  Cache-Control: public, max-age=0, must-revalidate', '  Service-Worker-Allowed: /');
  } else {
    // The runtime and preview are embedded by the IDE, so they must be cross-origin resources
    // and may only be framed by the IDE.
    lines.push(...common.map(h => '  ' + h));
    lines.push('  Cross-Origin-Resource-Policy: cross-origin');
    lines.push('  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()');
    lines.push('  Content-Security-Policy: frame-ancestors ' + origins.ide);
    lines.push('', '/index.html', '  Cache-Control: no-store', '', '/', '  Cache-Control: no-store');
  }
  return lines.join('\n') + '\n';
}

export function injectOrigins(html, origins) {
  const meta = '<meta name="beownir-origins" content="">';
  if (html.split(meta).length !== 2) throw new Error('the page must contain exactly one empty <meta name="beownir-origins"> tag');
  const content = 'runtime=' + origins.runtime + ';preview=' + origins.preview;
  return html.replace(meta, '<meta name="beownir-origins" content="' + content + '">');
}

function argValues(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) if (argv[i].startsWith('--')) out[argv[i].slice(2)] = argv[i + 1];
  return out;
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const args = argValues(process.argv.slice(2));
  const role = args.role || process.env.BEOWNIR_ROLE || 'ide';
  const origins = resolveOrigins({
    ide: args.ide || process.env.BEOWNIR_IDE_ORIGIN,
    runtime: args.runtime || process.env.BEOWNIR_RUNTIME_ORIGIN,
    preview: args.preview || process.env.BEOWNIR_PREVIEW_ORIGIN,
  });
  const source = path.resolve(root, args.in || 'o/site/index.html');
  const outDir = path.resolve(root, args.out || 'dist');
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'index.html'), injectOrigins(fs.readFileSync(source, 'utf8'), origins));
  fs.writeFileSync(path.join(outDir, '_headers'), headersFor(role, origins));
  fs.copyFileSync(path.join(root, 'o/site/coi-sw.js'), path.join(outDir, 'coi-sw.js'));
  console.log('role ' + role + ' written to ' + path.relative(root, outDir) + ' with runtime=' + origins.runtime + ' preview=' + origins.preview);
}
