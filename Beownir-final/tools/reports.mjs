export async function generate({ fast = false } = {}) {
  const started = Date.now();
  const html = fs.readFileSync(artifactPath, 'utf8');
  const gzipBytes = zlib.gzipSync(Buffer.from(html), { level: 9, mtime: 0 }).length;
  const manifest = readManifest(html);

  const { build } = await import('./build-standalone.mjs');
  const buildStarted = Date.now();
  const built = build();
  const buildMs = Date.now() - buildStarted;
  if (built.html !== html) throw new Error('the committed artifact is stale: run node tools/build-standalone.mjs');

  const { smokeArtifact } = await import('./standalone-smoke.mjs');
  const smoke = await smokeArtifact(artifactPath);

  const full = await buildReport();
  const compat = summarize(full);
  const differential = fast
    ? { passed: 0, total: 0, rows: [], skipped: true }
    : await runDifferential();
  const tests = fast
    ? { tests: 0, pass: 0, fail: 0, ms: 0, skipped: true, failed: [] }
    : runTests();
  const matrix = readJson('o/compat/framework-matrix.json');
  const baseline = readJson('o/compat/node-compat.json');

  const hostSource = fs.readFileSync(path.join(root, 'o/host/beownir-host.mjs'), 'utf8');
  const facts = {
    hostCsp: hostSource.includes('Content-Security-Policy'),
    tcpGuard: hostSource.includes('"/tcp/"') || hostSource.includes("'/tcp/'"),
  };

  const publishedPath = path.join(root, 'o', 'site', 'index.html');
  const published = fs.existsSync(publishedPath) ? fs.readFileSync(publishedPath) : Buffer.alloc(0);
  const { checkHeaders } = await import('./deploy-files.mjs');
  const deploy = {
    identical: published.equals(Buffer.from(html, 'utf8')),
    bytes: published.length,
    headersCurrent: checkHeaders().length === 0,
    headerBlocks: (fs.readFileSync(path.join(root, 'netlify.toml'), 'utf8').match(/\[\[headers\]\]/g) || []).length,
  };

  const files = {
    'NODE_COMPATIBILITY_REPORT.md': nodeReport({ compat, full, differential, tests, baseline }),
    'FRAMEWORK_COMPATIBILITY_REPORT.md': frameworkReport({ matrix }),
    'SECURITY_AUDIT.md': securityReport({ html, hostSource, facts }),
    'SINGLEFILE_BUILD_REPORT.md': singleFileReport({ html, manifest, sources: built.sources, assets: built.assets, smoke, buildMs, gzipBytes, build: built, deploy }),
    'PERFORMANCE_REPORT.md': performanceReport({ html, gzipBytes, buildMs, smoke, differential, tests, matrix, compat }),
  };
  for (const [name, contents] of Object.entries(files)) fs.writeFileSync(path.join(root, name), contents);
  return { files: Object.keys(files), ms: Date.now() - started, smoke, differential, tests, compat };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  const result = await generate({ fast: process.argv.includes('--fast') });
  console.log('wrote ' + result.files.join(', '));
  console.log('measured in ' + (result.ms / 1000).toFixed(1) + ' s');
  if (result.tests.skipped) console.log('tests and differential were skipped (--fast): the reports say so');
  else console.log('tests: ' + result.tests.pass + '/' + result.tests.tests + ' passed; differential: ' + result.differential.passed + '/' + result.differential.total + ' identical to Node');
  if (!result.smoke.ok) {
    console.error('the artifact smoke test failed:\n' + result.smoke.lines.join('\n'));
    process.exitCode = 1;
  }
}
