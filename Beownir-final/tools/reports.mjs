#!/usr/bin/env node
/**
 * Generates the five reports from measurements, never from prose about
 * measurements.
 *
 *   NODE_COMPATIBILITY_REPORT.md      live export census + differential results
 *   FRAMEWORK_COMPATIBILITY_REPORT.md the committed framework matrix, verbatim
 *   SECURITY_AUDIT.md                 mechanisms found in the code, with gaps
 *   SINGLEFILE_BUILD_REPORT.md        a fresh build + manifest + smoke run
 *   PERFORMANCE_REPORT.md             sizes and timings measured in this run
 *
 * Every number below is produced by running the project in this checkout; the
 * narrative sections are explicit about what was *not* tested. `--fast` skips
 * the test suite and the differential run (they are the slow parts) and says so
 * in the output instead of pretending they ran.
 *
 * Usage:
 *   node tools/reports.mjs            # measure everything and write the reports
 *   node tools/reports.mjs --fast     # skip the test suite and differential run
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { buildReport, summarize } from './compat-report.mjs';
import { readManifest } from './build-standalone.mjs';

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const artifactPath = path.join(root, 'beownir-standalone.html');
const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const mib = bytes => (bytes / 1048576).toFixed(2) + ' MiB';
const pct = value => (value * 100).toFixed(1) + '%';
const stamp = () => new Date().toISOString();

function readJson(relative) {
  return JSON.parse(fs.readFileSync(path.join(root, relative), 'utf8'));
}

function runTests() {
  const started = Date.now();
  let output = '';
  try {
    output = execFileSync(process.execPath, ['--test', '--test-reporter=tap', 'test/*.test.mjs'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 * 1024 * 1024 });
  } catch (error) {
    output = String(error.stdout || '') + String(error.stderr || '');
  }
  const count = pattern => Number((pattern.exec(output) || [])[1] || 0);
  return {
    tests: count(/^# tests (\d+)$/m),
    pass: count(/^# pass (\d+)$/m),
    fail: count(/^# fail (\d+)$/m),
    ms: Date.now() - started,
    failed: [...output.matchAll(/^not ok \d+ - (.+)$/gm)].map(match => match[1]),
  };
}

async function runDifferential() {
  const { loadRuntime } = await import('../test/helpers/runtime.mjs');
  const { runDifferential } = await import('./node-differential.mjs');
  return runDifferential({ loadRuntime });
}

function table(headers, rows) {
  const widths = headers.map((header, index) => Math.max(header.length, ...rows.map(row => String(row[index] ?? '').length)));
  const line = cells => '| ' + cells.map((cell, index) => String(cell ?? '').padEnd(widths[index])).join(' | ') + ' |';
  return [line(headers), '| ' + widths.map(width => '-'.repeat(width)).join(' | ') + ' |', ...rows.map(line)].join('\n');
}

